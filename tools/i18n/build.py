#!/usr/bin/env python3
"""Builds the game's translations from tools/i18n/strings.py.

  python3 tools/i18n/build.py [web.html ...]

Writes game/scripts/i18n_data.gd (Godot) and, for each web page given, replaces the block between
/*I18N-DATA*/ and /*END-I18N-DATA*/ with the same table as JavaScript.
Fonts: python3 tools/i18n/fonts.py (needs fonttools) cuts the language fonts down to the letters used here.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import strings as S  # noqa: E402


def check():
    seen = set()
    for row in S.S:
        assert len(row) == len(S.LANGS), row[0]
        assert row[0] not in seen, "duplicate: " + row[0]
        seen.add(row[0])
        want = sorted(re.findall(r"\{\d\}", row[0]))
        for lang, text in zip(S.LANGS[1:], row[1:]):
            assert sorted(re.findall(r"\{\d\}", text)) == want, (row[0], lang, text)


def table():
    return {lang: {row[0]: row[i] for row in S.S} for i, lang in enumerate(S.LANGS) if lang != "en"}


def gd_str(s):
    return json.dumps(s, ensure_ascii=False)


def write_gd(path):
    t = table()
    out = ["# Generated by tools/i18n/build.py from tools/i18n/strings.py. Do not edit by hand.",
           "extends RefCounted", "",
           "const LANGS := " + gd_str(S.LANGS),
           "const NATIVE := " + gd_str(S.NATIVE),
           "const MONTHS := " + gd_str({k: {"names": v[0], "fmt": v[1]} for k, v in S.MONTHS.items()}),
           "const DATA := {"]
    for lang, d in t.items():
        out.append("\t%s: {" % gd_str(lang))
        for k, v in d.items():
            out.append("\t\t%s: %s," % (gd_str(k), gd_str(v)))
        out.append("\t},")
    out.append("}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


def web_block():
    data = {"langs": S.LANGS, "native": S.NATIVE, "months": {k: {"names": v[0], "fmt": v[1]} for k, v in S.MONTHS.items()}, "t": table()}
    return "/*I18N-DATA*/const I18N = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";/*END-I18N-DATA*/"


def patch_web(path):
    html = open(path, encoding="utf-8").read()
    new, n = re.subn(r"/\*I18N-DATA\*/.*?/\*END-I18N-DATA\*/", lambda m: web_block(), html, flags=re.S)
    assert n == 1, "marker not found in " + path
    open(path, "w", encoding="utf-8").write(new)


if __name__ == "__main__":
    check()
    write_gd(os.path.join(ROOT, "game", "scripts", "i18n_data.gd"))
    for p in sys.argv[1:]:
        patch_web(p)
    print("ok:", len(S.S), "texts x", len(S.LANGS), "languages")
